using System.Globalization;
using System.IO;
using System.Text;
using UnityEditor;

namespace SpectralPathTracer
{
    public static class CieShaderTables
    {
        private const string OutputPath = "Assets/SpectralPathTracer/Shaders/Include/Spectrum/CieTables.hlsl";

        /**
         * <summary>
         * Writes the matching functions and D65 from Cie into HLSL arrays for the shaders.
         * </summary>
         */
        [MenuItem("Tools/Spectral Path Tracer/Generate CIE Shader Table")]
        public static void Generate()
        {
            var text = new StringBuilder();
            text.AppendLine("// Generated by Tools > Spectral Path Tracer > Generate CIE Shader Table from Cie.X, Cie.Y, Cie.Z and Cie.D65.");
            text.AppendLine("// Regenerate instead of editing by hand.");
            text.AppendLine();
            text.AppendLine("/**");
            text.AppendLine(" * <summary>");
            text.AppendLine(" * The CIE 1931 2 degree matching functions at 1 nm and the D65 illuminant at 5 nm.");
            text.AppendLine(" * </summary>");
            text.AppendLine(" */");
            text.AppendLine();

            text.AppendLine("#ifndef SPT_CIE_TABLES_INCLUDED");
            text.AppendLine("#define SPT_CIE_TABLES_INCLUDED");
            text.AppendLine();
            text.AppendLine($"static const float CIE_FIRST_WAVELENGTH = {Cie.FirstWavelength}.0f;");
            text.AppendLine($"static const uint CIE_SAMPLE_COUNT = {Cie.SampleCount}u;");
            text.AppendLine();


            text.AppendLine($"static const float3 CIE_XYZ[{Cie.SampleCount}] =");
            text.AppendLine("{");
            for (int row = 0; row < Cie.SampleCount; row++)
            {
                string separator = row < Cie.SampleCount - 1 ? "," : "";
                text.AppendLine($"    float3({Literal(Cie.X[row])}, {Literal(Cie.Y[row])}, {Literal(Cie.Z[row])}){separator}");
            }

            text.AppendLine("};");
            text.AppendLine();


            text.AppendLine($"static const float CIE_D65_FIRST = {Cie.D65First}.0f;");
            text.AppendLine($"static const float CIE_D65_STEP = {Cie.D65Step}.0f;");
            text.AppendLine($"static const uint CIE_D65_COUNT = {Cie.D65.Length}u;");
            text.AppendLine($"static const float CIE_D65_SCALE = {Literal(D65Scale())}; // rescales D65 so a light of white 1 has Y = 1");
            text.AppendLine();

            text.AppendLine($"static const float CIE_D65[{Cie.D65.Length}] =");
            text.AppendLine("{");
            for (int row = 0; row < Cie.D65.Length; row++)
            {
                string separator = row < Cie.D65.Length - 1 ? "," : "";
                text.AppendLine($"    {Literal(Cie.D65[row])}{separator}");
            }

            text.AppendLine("};");
            text.AppendLine();
            text.AppendLine("#endif");

            File.WriteAllText(OutputPath, text.ToString());
            AssetDatabase.ImportAsset(OutputPath);
        }

        /**
         * <summary>
         * The factor that makes D65, divided by the y-bar integral like every sample, come out at Y = 1.
         * </summary>
         * <returns>The integral of y-bar over the integral of D65 times y-bar.</returns>
         */
        private static float D65Scale()
        {
            float d65Y = 0f;
            for (int lambda = Cie.FirstWavelength; lambda <= Cie.LastWavelength; lambda++)
                d65Y += Cie.D65At(lambda) * Cie.MatchingFunctions(lambda).y; // 1 nm steps, like the spectrum check


            return Cie.YIntegral / d65Y;
        }

        /**
         * <summary>
         * Formats a float as an HLSL literal that reads back as the same float.
         * </summary>
         * <param name="value">The value.</param>
         * <returns>The literal, with an f suffix.</returns>
         */
        private static string Literal(float value)
        {
            // invariant, so a comma locale can't turn the decimal point into a separator
            string literal = value.ToString("R", CultureInfo.InvariantCulture);

            // hlsl needs a decimal point or an exponent before the f
            if (literal.IndexOfAny(new[] { '.', 'E' }) < 0)
                literal += ".0";


            return literal + "f";
        }
    }
}
